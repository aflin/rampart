#!/bin/sh
#
# Start the Mini IDE: a browser-based editor, file navigator and terminal
# for the files in this web server directory.
#
#   ./start-mini-ide.sh [start|stop|restart|status|setup]
#
# The first start asks for a password, whether to listen on all
# interfaces (bindAll) and which port to use.  Run "setup" to change them.
# Set RAMPART=/path/to/rampart to use a rampart other than the one in PATH.

cd "$(dirname "$0")" || exit 1

CONF=mini-ide-conf.js
SETTINGS=ide/data/ide-settings.json

if [ ! -d ide ]; then
    echo "The Mini IDE is not installed here (no ide/ directory)." >&2
    exit 1
fi
RAMPART=${RAMPART:-$(command -v rampart)}

if [ -z "$RAMPART" ]; then
    echo "rampart was not found in PATH.  Set RAMPART=/path/to/rampart" >&2
    exit 1
fi

if [ "$(id -u)" = 0 ]; then
    echo "The Mini IDE gives a shell to whoever logs in.  Do not run it as root." >&2
    exit 1
fi

restore_tty() {
    stty echo 2>/dev/null
}

setup() {
    if [ ! -t 0 ]; then
        echo "Setup needs a terminal.  Run $0 setup interactively." >&2
        exit 1
    fi
    echo "Mini IDE setup"
    trap 'restore_tty; echo; exit 1' INT TERM
    while :; do
        printf "Password: "
        stty -echo; read -r pass1; restore_tty; echo
        if [ ${#pass1} -lt 4 ]; then
            echo "Password must be at least 4 characters."
            continue
        fi
        printf "Password again: "
        stty -echo; read -r pass2; restore_tty; echo
        [ "$pass1" = "$pass2" ] && break
        echo "Passwords do not match."
    done
    trap - INT TERM

    printf "Listen on all interfaces (bindAll)? Otherwise localhost only [y/N]: "
    read -r bindall
    case "$bindall" in
        [yY]*) bindall=y ;;
        *)     bindall=n ;;
    esac

    while :; do
        printf "Port [8089]: "
        read -r port
        port=${port:-8089}
        case "$port" in
            *[!0-9]*) echo "Port must be a number." ;;
            *) if [ "$port" -ge 1024 ] && [ "$port" -le 65535 ]; then break; fi
               echo "Port must be between 1024 and 65535." ;;
        esac
    done

    printf '%s\n%s\n%s\n' "$pass1" "$bindall" "$port" | "$RAMPART" "$CONF" setup || exit 1
}

# The first start builds the searchable documentation, if it has been copied
# in (ide/docs/html and ide/apps/docs/rsearch.js, see
# rampart_docs/copy_to_rampart.sh): rsearch.js writes the pages to
# ide/html/docs/ and the search index to ide/data/docs/.
build_docs() {
    [ -f ide/html/docs/index.html ] && return
    [ -f ide/apps/docs/rsearch.js ] && [ -d ide/docs/html ] || return
    echo "Building documentation pages (ide/html/docs) and search index (ide/data/docs)"
    mkdir -p ide/data/docs
    "$RAMPART" ide/apps/docs/rsearch.js || echo "Building the documentation failed; starting anyway." >&2
}

# AGENTS.md (and CLAUDE.md, a link to it) describe this server for coding
# agents.  Rewritten on every start since the port and host can change.
# A hand-written AGENTS.md or CLAUDE.md is never replaced.
AGENTS_MARK='<!-- Generated by start-mini-ide.sh on every start.  Edits here are lost. -->'
write_agents() {
    if [ -f AGENTS.md ] && [ "$(head -n 1 AGENTS.md)" != "$AGENTS_MARK" ]; then
        echo "AGENTS.md was not written by start-mini-ide.sh; leaving it alone." >&2
        return
    fi
    conf=$("$RAMPART" -c 'var s=JSON.parse(rampart.utils.readFile(process.argv[3],{returnString:true}));rampart.utils.printf("%d %s",s.port,s.bindAll?"all":"local")' "$SETTINGS") || return
    port=${conf% *}
    bind=${conf#* }
    if [ "$bind" = all ]; then
        where="on port $port, listening on all interfaces (0.0.0.0 and [::]).
From this machine it is at http://localhost:$port/"
    else
        where="on port $port, listening on localhost only (127.0.0.1 and [::1]).
It is at http://localhost:$port/"
    fi
    cat > AGENTS.md <<EOF
$AGENTS_MARK
# Rampart web server

This is a [Rampart](https://rampart.dev) web server.  It is currently running
$where
(the IDE is at http://localhost:$port/ide/).  It was started by
\`./start-mini-ide.sh\`, which adds the Mini IDE.  The same site runs
without the IDE with \`rampart web_server_conf.js start\` (default port 8088).

## Layout

| Path | Purpose |
|------|---------|
| \`web_server_conf.js\` | Server configuration.  \`rampart web_server_conf.js [start\\|stop\\|restart\\|status]\` |
| \`html/\` | Static files, served at \`/\` |
| \`apps/\` | JavaScript server modules, served at \`/apps/\` (see below) |
| \`wsapps/\` | Websocket modules, served at \`ws://host:port/wsapps/\` |
| \`data/\` | Databases and other data.  Scripts find it as \`serverConf.dataRoot\` |
| \`logs/\` | \`access.log\` and \`error.log\` |
| \`ide/\` | The Mini IDE (see below) |
| \`mini-ide-conf.js\`, \`start-mini-ide.sh\` | Start the same server with the IDE added at \`/ide/\` |

Server modules in \`apps/\`:

- \`apps/name.js\` with \`module.exports = function(req) {...}\` answers
  \`/apps/name.html\`, \`/apps/name.json\` and so on.  The returned object's key
  sets the content type, e.g. \`return {json: obj}\` or \`return {html: text}\`.
- \`module.exports = {"/page.html": f1, "/data.json": f2}\` answers
  \`/apps/name/page.html\` and \`/apps/name/data.json\`.
- Modules are reloaded when the file changes; no server restart is needed.
- Each server thread has its own JavaScript context.  Keep state in the module
  or in a database under \`serverConf.dataRoot\`, not in closures shared at startup.

\`html/\`, \`apps/\`, \`wsapps/\`, \`data/\` and \`logs/\` are the same whether the
server is started with or without the IDE.

## The ide/ directory

\`ide/\` holds the Mini IDE and its copy of the documentation.  It is not part of
the site and is not intended to be included in any final product: removing
\`ide/\` (plus \`mini-ide-conf.js\` and \`start-mini-ide.sh\`) leaves the plain web
server.  Do not write new scripts or files in \`ide/\` unless they are for the
IDE itself.  Site code goes in \`html/\`, \`apps/\` and \`wsapps/\`.

## Documentation

- Rampart documentation source: \`ide/docs/source/\` (reStructuredText, one file
  per module, e.g. \`rampart-server.rst\`, \`rampart-sql.rst\`, \`rampart-utils.rst\`).
- How to program in Rampart: \`ide/docs/source/overview.md\`.  Read it before
  writing Rampart code; Rampart is not Node.js.
- The built, searchable docs are served at \`/ide/docs/\` while the IDE is running.
EOF
    if [ -L CLAUDE.md ] || [ ! -e CLAUDE.md ]; then
        ln -sf AGENTS.md CLAUDE.md
    else
        echo "CLAUDE.md exists and is not a link; not linking it to AGENTS.md." >&2
    fi
}

cmd=${1:-start}

case "$cmd" in
    setup)
        setup
        echo "Restart the IDE ($0 restart) if it is running and the port or bindAll changed."
        exit 0
        ;;
    start|restart)
        [ -f "$SETTINGS" ] || setup
        build_docs
        write_agents
        ;;
esac

exec "$RAMPART" "$CONF" "$cmd"
